-- ============================================================
-- 061_rename_tansan_to_drink.sql
-- '탄산음료' → '음료수' 이름 변경 및 활성화
--
-- 비개발자 설명:
--   마켓 상품 목록에서 "탄산음료"를 "음료수"로 바꾸고,
--   비활성화되어 있더라도 다시 노출되도록 활성화합니다.
-- ============================================================

update public.store_items
set
  name      = '음료수',
  is_active = true
where
  name = '탄산음료'
  and item_type = 'real';
